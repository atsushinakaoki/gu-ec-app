-- =====================================================================
-- マイグレーション 002  確認画面の内容を冪等キーに結び付ける
--
-- 【追加の理由】
--   ChatGPT によるコードレビューで指摘された欠陥への対処。
--
--   確認画面を開いた後、別のタブで中身を同額のまま差し替えると
--   （すそ上げの丈 700mm → 650mm など）、古い確認画面から押した
--   「注文を確定する」で、差し替え後の内容が注文されていた。
--   金額しか照合しておらず、利用者が確認した内容と注文内容が
--   一致することを保証していなかった。
--
--   確認画面を出した時点の冪等キーと fingerprint を保存し、
--   注文確定の時点で完全に一致することを要求する。
--
-- 実行:  python db/run_sql.py db/migrate_002_summary_binding.sql
-- 2回目の実行では「Duplicate column」で NG になるが、害はない。
-- =====================================================================

USE gu_ec_nakaoki;

ALTER TABLE checkout
  ADD COLUMN summary_idempotency_key VARCHAR(64) NULL COMMENT '確認画面で発行した冪等キー',
  ADD COLUMN summary_fingerprint     VARCHAR(64) NULL COMMENT '確認画面を出した時点の注文内容のハッシュ値';
